/// App language (English / Arabic). Changing it rebuilds the whole UI (see main.dart) and flips to RTL.
class Lang extends ChangeNotifier {
  Lang._();
  static final Lang i = Lang._();

  String code = 'en';
  /// Set when the user switches language so the app comes back on the Settings tab instead of Home.
  bool openSettingsAfterRestart = false;
  SharedPreferences? _prefs;

  bool get isAr => code == 'ar';
  Locale get locale => Locale(code);

  Future<void> init() async {
    _prefs = await SharedPreferences.getInstance();
    final saved = _prefs!.getString('lang');
    if (saved == 'ar' || saved == 'en') {
      code = saved!;
    } else {
      code = WidgetsBinding.instance.platformDispatcher.locale.languageCode == 'ar' ? 'ar' : 'en';
    }
  }

  Future<void> set(String c, {bool fromSettings = false}) async {
    if (c == code) return;
    code = c;
    openSettingsAfterRestart = fromSettings;
    await _prefs?.setString('lang', c);
    notifyListeners();
  }
}

/// Translate a UI string. Unknown strings (user data, numbers) are returned unchanged.
String tr(String s) {
  if (!Lang.i.isAr || s.isEmpty) return s;
  final hit = kAr[s];
  if (hit != null) return hit;
  final t = s.trim();
  if (t.isEmpty) return s;
  final h2 = kAr[t];
  if (h2 != null) return s.replaceFirst(t, h2);
  return _trServerMessage(s);
}

/// Translate a template and fill in {placeholders}: tf('{n} Active', {'n': 3}).
String tf(String key, Map<String, Object> args) {
  var out = Lang.i.isAr ? (kAr[key] ?? key) : key;
  args.forEach((k, v) => out = out.replaceAll('{$k}', '$v'));
  return out;
}

/// Money / energy formatting with localised units.
String egp(double v, [int digits = 2]) => '${v.toStringAsFixed(digits)} ${tr('EGP')}';
String kwhText(double v, [int digits = 2]) => '${v.toStringAsFixed(digits)} ${tr('kWh')}';

/// Alert titles/messages are generated by the server in English; map the known ones.
final List<(RegExp, String)> _serverPatterns = [
  (RegExp(r'^Smart Plug (\d+)$'), 'plug_name'),
  (RegExp(r'^(.+) was turned (on|off)$'), 'device_turned'),
  (RegExp(r'^(.+) exceeded (\d+(?:\.\d+)?)W \(reading: (\d+(?:\.\d+)?)W\)$'), 'exceeded'),
  (RegExp(r'^Power exceeded (\d+)W$'), 'power_exceeded'),
  (RegExp(r'^(.+) is drawing (\d+)W, (\d+)% above its rated (\d+)W\. Check the appliance\.$'), 'above_rated'),
  (RegExp(r'^Only (\d+(?:\.\d+)?) EGP is left on your electricity card\.$'), 'card_low'),
  (RegExp(r'^You have used (\d+) kWh this month and moved into tier (\d+) \((\d+(?:\.\d+)?) EGP/kWh\)\.$'), 'tier_moved'),
  (RegExp(r'^At this pace you will use about (\d+) kWh this month and enter a tier at (\d+(?:\.\d+)?) EGP/kWh \((\d+) kWh left in your current tier\)\.$'), 'tier_pace'),
];

String _trServerMessage(String s) {
  for (final p in _serverPatterns) {
    final mt = p.$1.firstMatch(s);
    if (mt == null) continue;
    switch (p.$2) {
      case 'plug_name':
        return 'القابس الذكي ${mt.group(1)}';
      case 'device_turned':
        return '${tr(mt.group(1)!)} ${mt.group(2) == 'on' ? 'تم تشغيله' : 'تم إيقافه'}';
      case 'exceeded':
        return '${tr(mt.group(1)!)} تجاوز ${mt.group(2)}W (القراءة: ${mt.group(3)}W)';
      case 'power_exceeded':
        return 'القدرة تجاوزت ${mt.group(1)}W';
      case 'above_rated':
        return '${tr(mt.group(1)!)} يسحب ${mt.group(2)}W أي أعلى بنسبة ${mt.group(3)}% من قدرته المقننة ${mt.group(4)}W. افحص الجهاز.';
      case 'card_low':
        return 'تبقّى ${mt.group(1)} ج.م فقط على كارت الكهرباء.';
      case 'tier_moved':
        return 'استهلكت ${mt.group(1)} ك.و.س هذا الشهر وانتقلت إلى الشريحة ${mt.group(2)} (${mt.group(3)} ج.م/ك.و.س).';
      case 'tier_pace':
        return 'بهذا المعدل ستستهلك حوالي ${mt.group(1)} ك.و.س هذا الشهر وتدخل شريحة سعرها ${mt.group(2)} ج.م/ك.و.س (متبقي ${mt.group(3)} ك.و.س في شريحتك الحالية).';
    }
  }
  return s;
}

InlineSpan _trSpan(InlineSpan s) {
  if (s is TextSpan) {
    return TextSpan(
      text: s.text == null ? null : tr(s.text!),
      style: s.style,
      recognizer: s.recognizer,
      children: s.children?.map(_trSpan).toList(),
    );
  }
  return s;
}

/// Drop-in replacement for Flutter's Text that translates its content (screens import
/// material.dart with `hide Text` and this file instead). Works inside `const` trees.
class Text extends StatelessWidget {
  final String? data;
  final InlineSpan? span;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final bool? softWrap;
  const Text(String this.data, {super.key, this.style, this.textAlign, this.maxLines, this.overflow, this.softWrap}) : span = null;
  const Text.rich(InlineSpan this.span, {super.key, this.style, this.textAlign, this.maxLines, this.overflow, this.softWrap}) : data = null;

  @override
  Widget build(BuildContext context) {
    if (span != null) {
      return m.Text.rich(_trSpan(span!), style: style, textAlign: textAlign, maxLines: maxLines, overflow: overflow, softWrap: softWrap);
    }
    return m.Text(tr(data!), style: style, textAlign: textAlign, maxLines: maxLines, overflow: overflow, softWrap: softWrap);
  }
}

/// Small "العربية | English" switch used on the login screen.
class LangToggle extends StatelessWidget {
  const LangToggle({super.key});
  @override
  Widget build(BuildContext context) {
    final ar = Lang.i.isAr;
    return GestureDetector(
      onTap: () => Lang.i.set(ar ? 'en' : 'ar'),
      child: Container(
        padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 7),
        decoration: BoxDecoration(
          color: Colors.white.withOpacity(0.06),
          borderRadius: BorderRadius.circular(99),
          border: Border.all(color: Colors.white.withOpacity(0.14)),
        ),
        child: Row(mainAxisSize: MainAxisSize.min, children: [
          const Icon(Icons.language_rounded, size: 15, color: Color(0xFF8A93A6)),
          const SizedBox(width: 6),
          m.Text(ar ? 'English' : 'العربية', style: const TextStyle(fontSize: 12, fontWeight: FontWeight.w700, color: Color(0xFFF3F5F9))),
        ]),
      ),
    );
  }
}

/// Parses a number typed by the user, accepting Arabic-Indic digits and ',' or '٫' as the decimal mark.
double? parseNum(String s) {
  var t = s.trim();
  const ar = '٠١٢٣٤٥٦٧٨٩';
  for (var i = 0; i < ar.length; i++) {
    t = t.replaceAll(ar[i], '$i');
  }
  t = t.replaceAll('٫', '.').replaceAll(',', '.');
  return double.tryParse(t);
}
